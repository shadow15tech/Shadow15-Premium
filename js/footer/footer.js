/*==========================================================
                    FOOTER
==========================================================*/

document.addEventListener(

    "DOMContentLoaded",

    ()=>{

        /*==========================================================
                            GSAP
        ==========================================================*/

        if(

            typeof gsap==="undefined" ||

            typeof ScrollTrigger==="undefined"

        ){

            return;

        }

        gsap.registerPlugin(

            ScrollTrigger

        );

        /*==========================================================
                            TIMELINE
        ==========================================================*/

        const footerTimeline =

        gsap.timeline({

            paused:true,

            defaults:{

                ease:"power3.out"

            }

        });

        footerTimeline

        /*==========================================================
                            TOP
        ==========================================================*/

        .from(

            ".footer-top",

            {

                opacity:0,

                y:80,

                duration:.9

            }

        )

        /*==========================================================
                            COLUMNS
        ==========================================================*/

        .from(

            ".footer-column",

            {

                opacity:0,

                y:50,

                stagger:.15,

                duration:.7

            },

            "-=.35"

        )

        /*==========================================================
                            SOCIAL
        ==========================================================*/

        .from(

            ".footer-social",

            {

                opacity:0,

                y:40,

                duration:.7

            },

            "-=.4"

        )

        /*==========================================================
                            BOTTOM
        ==========================================================*/

        .from(

            ".footer-bottom",

            {

                opacity:0,

                y:25,

                duration:.6

            },

            "-=.35"

        );

        /*==========================================================
                            SCROLLTRIGGER
        ==========================================================*/

        ScrollTrigger.create({

            trigger:".footer",

            start:"top 80%",

            once:true,

            animation:footerTimeline

        });

    }

);